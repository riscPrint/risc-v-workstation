#!/bin/sh
# Patch the riscv-tests runtime for a bare-metal host without HTIF console I/O.
# Keep the original ROI counter reads. Export the deltas as two 64-bit words.
set -eu
test "$#" -eq 1 || { echo 'usage: patch_syscalls.sh syscalls.c' >&2; exit 1; }
input="$1"
test "$(grep -c '^  tohost = (uintptr_t)magic_mem;$' "$input")" = 1 || {
  echo 'patch_syscalls: syscall() changed upstream' >&2; exit 1;
}
test "$(grep -c '^void setStats(int enable)$' "$input")" = 1 || {
  echo 'patch_syscalls: setStats() changed upstream' >&2; exit 1;
}
if grep -q 'bench_stats\|setStats_rt' "$input"; then
  echo 'patch_syscalls: input is already patched or has conflicting names' >&2
  exit 1
fi
echo '// Generated by Arch/bench/rt/patch_syscalls.sh. Do not edit.'
sed -e 's|^  tohost = (uintptr_t)magic_mem;$|  return 0; /* no HTIF console host */|' \
    -e 's|^void setStats(int enable)$|static void setStats_rt(int enable)|' "$input"
cat <<'C'

volatile uint64_t bench_stats[2] __attribute__((aligned(8)));

#if __riscv_xlen == 32
static uint64_t read_cycle64(void) {
  uint32_t hi, lo, again;
  do {
    __asm__ volatile ("csrr %0, mcycleh" : "=r"(hi));
    __asm__ volatile ("csrr %0, mcycle" : "=r"(lo));
    __asm__ volatile ("csrr %0, mcycleh" : "=r"(again));
  } while (hi != again);
  return ((uint64_t)hi << 32) | lo;
}
static uint64_t read_instret64(void) {
  uint32_t hi, lo, again;
  do {
    __asm__ volatile ("csrr %0, minstreth" : "=r"(hi));
    __asm__ volatile ("csrr %0, minstret" : "=r"(lo));
    __asm__ volatile ("csrr %0, minstreth" : "=r"(again));
  } while (hi != again);
  return ((uint64_t)hi << 32) | lo;
}
#endif

void setStats(int enable)
{
#if defined(RVW_NO_COUNTERS)
  (void)enable;
#elif __riscv_xlen == 32
  static uint64_t start_cycles, start_instret;
  uint64_t cycles = read_cycle64(), instret = read_instret64();
  if (enable) { start_cycles = cycles; start_instret = instret; }
  else { bench_stats[0] = cycles - start_cycles; bench_stats[1] = instret - start_instret; }
#else
  setStats_rt(enable);
  if (!enable) {
    bench_stats[0] = counters[0]; /* mcycle delta */
    bench_stats[1] = counters[1]; /* minstret delta */
  }
#endif
}
C

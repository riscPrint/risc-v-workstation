"""The agent playbook: ordered rvw/MCP calls with decision points, one data file.

`docs/AGENT_SETUP.md` embeds `markdown()` between its guide markers, so the human
document and the MCP resource come from the same data. A fast test checks both.
"""
from __future__ import annotations

import json
from pathlib import Path

SCHEMA = 'rvw.agent-guide/1'
DATA = Path(__file__).with_name('playbook.json')
BEGIN = '<!-- rvw agent guide: begin (generated by `rvw agent guide --markdown`; do not edit) -->'
END = '<!-- rvw agent guide: end -->'
TERMINAL = {'done', 'stop'}


def load():
    data = json.loads(DATA.read_text())
    problems = validate(data)
    if problems:
        raise ValueError('; '.join(problems))
    return data


def validate(data):
    problems = []
    if data.get('schema') != SCHEMA:
        problems.append(f'schema must be {SCHEMA}')
    workflows = {w['id'] for w in data['workflows']}
    for workflow in data['workflows']:
        steps = [s['id'] for s in workflow['steps']]
        if len(set(steps)) != len(steps):
            problems.append(f'{workflow["id"]}: duplicate step ids')
        for step in workflow['steps']:
            if not step.get('manual') and not step.get('cli'):
                problems.append(f'{workflow["id"]}.{step["id"]}: a step needs cli or manual')
            for decision in step.get('decide', []):
                target = decision['then']
                if target not in TERMINAL and target not in steps and target not in workflows:
                    problems.append(f'{workflow["id"]}.{step["id"]}: unknown target {target!r}')
    return problems


def select(data, workflow=None):
    if workflow is None:
        return data
    for w in data['workflows']:
        if w['id'] == workflow:
            return {'schema': SCHEMA, 'conventions': data['conventions'], 'workflows': [w]}
    raise ValueError(f'unknown workflow {workflow!r}; known: {", ".join(w["id"] for w in data["workflows"])}')


def _call(step):
    parts = []
    if step.get('cli'):
        parts.append('`rvw ' + ' '.join(step['cli']) + '`')
    if step.get('mcp'):
        parts.append('MCP `' + step['mcp']['tool'] + '`')
    return ' / '.join(parts) if parts else '(manual)'


def markdown(data=None):
    data = data or load()
    lines = [BEGIN, '', '## Agent workflows', '',
             'Machine-readable form: `rvw agent guide --json`, MCP tool `agent_guide`, '
             'MCP resource `rvw://agent/guide`.', '']
    for key, text in data['conventions'].items():
        lines.append(f'- {key.replace("_", " ").capitalize()}: {text}')
    for workflow in data['workflows']:
        lines += ['', f'### {workflow["title"]} (`{workflow["id"]}`)', '', workflow['when'], '']
        for number, step in enumerate(workflow['steps'], 1):
            optional = ' (optional)' if step.get('optional') else ''
            lines.append(f'{number}. **{step["id"]}**{optional}: {step["do"]} {_call(step)}')
            for decision in step.get('decide', []):
                note = f' {decision["note"]}' if decision.get('note') else ''
                lines.append(f'   - If {decision["if"]}: go to `{decision["then"]}`.{note}')
    lines += ['', END]
    return '\n'.join(lines) + '\n'


def embed(text, block):
    """Replace the guide block in a document's text (append it if the markers are absent)."""
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        return head + block.rstrip('\n') + tail
    return text.rstrip('\n') + '\n\n' + block

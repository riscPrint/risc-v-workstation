"""Timing-constraint intent from clock-domain data: SDC generation and SDC checks.

This checks logical intent against elaborated endpoints. It is not routed timing signoff."""
import fnmatch
import re
import shlex

from . import structural
from .graph import Design


SAFE = {'sync_2ff', 'sync_3ff', 'sync_4ff', 'sync_5ff', 'sync_6ff', 'gray_sync', 'qualified_data'}
UNSAFE = {'unsynchronized', 'multi_bit', 'glitch_before_sync', 'first_stage_fanout'}
MAXDELAY = re.compile(r'crossClockMaxDelay\(cycles=Int\((\d+)\),useTargetClock=Boolean\((true|false)\)\)')
FALSEPATH = re.compile(r'crossClockFalsePath\(destType=[\w.$]*?(\w+)\$?,source=(?:scala\.Some\(value=signal ([\w.$]+)\)|scala\.None\$?)')
SYNCTAG = re.compile(r'ClockSyncTag\(a=signal ([\w.$]+),b=signal ([\w.$]+)\)')


def options(cfg):
    cfg = cfg or {}
    allowed = {'clocks', 'generated', 'multicycle', 'check', 'register_pattern', 'output_pin'}
    if not isinstance(cfg, dict) or set(cfg) - allowed:
        raise ValueError('sdc settings keys must be in: ' + ', '.join(sorted(allowed)))
    for name, c in (cfg.get('clocks') or {}).items():
        if not isinstance(c, dict) or set(c) - {'period_ns'} or type(c.get('period_ns')) not in (int, float) \
                or c['period_ns'] <= 0:
            raise ValueError(f'sdc.clocks.{name} needs a positive period_ns')
    for name, g in (cfg.get('generated') or {}).items():
        if not isinstance(g, dict) or set(g) - {'source', 'multiply_by', 'divide_by'} or not isinstance(g.get('source'), str):
            raise ValueError(f'sdc.generated.{name} needs source and optional multiply_by/divide_by')
    for m in cfg.get('multicycle') or []:
        if (not isinstance(m, dict) or set(m) - {'from', 'to', 'setup', 'hold', 'reason'}
                or not all(isinstance(m.get(k), str) and m[k].strip() for k in ('from', 'to', 'reason'))
                or type(m.get('setup')) is not int or m['setup'] < 2
                or type(m.get('hold', m['setup'] - 1)) is not int):
            raise ValueError('sdc.multicycle rows need from, to, setup >= 2, reason and optional hold')
    return cfg


class Names:
    """Netlist object names for SDC. Register cells follow `register_pattern`."""

    def __init__(self, design, cfg):
        self.d = design
        self.pattern = cfg.get('register_pattern', '{path}_reg*')
        self.pin = cfg.get('output_pin', 'Q')

    def hier(self, i):
        s = self.d.signals[i]
        comp = self.d.components.get(s['component_id']) or {}
        parts, c = [], comp
        while c and c.get('depth', 0) > 0:
            parts.append(c['name'])
            c = self.d.components.get(c['parent_id'])
        return '/'.join([*reversed(parts), s['name']])

    def cell(self, i):
        return self.pattern.format(path=self.hier(i))

    def cells(self, i):
        return '[get_cells {%s}]' % self.cell(i)


def analyze(db, cfg, intent):
    cfg = options(cfg)
    design = Design(db.conn)
    s = structural.analyze(db, intent)
    names = Names(design, cfg)
    clocks = s['cdc']['clocks']
    findings, lines = [], ['# Generated by rvw lint (sdc backend). Logical intent only; not timing signoff.']

    def emit(rule, endpoint, message, severity='warning', **extra):
        sig = design.signals.get(design.by_path.get(endpoint, -1)) or {}
        findings.append(dict(rule=rule, severity=severity, endpoint=endpoint, file=sig.get('file'),
                             line=sig.get('line'), message=message, **extra))

    # Periods: settings first, then SpinalDB clock_frequencies when the table exists.
    periods = {k: v['period_ns'] for k, v in (cfg.get('clocks') or {}).items()}
    if 'clock_frequencies' in design.tables:
        for cd, hz in db.conn.execute('SELECT clock_domain_id, hz FROM clock_frequencies WHERE hz IS NOT NULL'):
            dom = design.domains.get(cd) or {}
            if dom.get('clock') and dom['clock'] not in periods:
                periods[dom['clock']] = round(1e9 / float(hz), 6)
    for k in periods:
        if k not in {c['clock'] for c in clocks}:
            raise ValueError(f'sdc.clocks names an unknown clock: {k}')

    # One SDC clock per distinct clock net.
    defined, by_clock = {}, {}
    for c in clocks:
        by_clock.setdefault(c['clock'], c)
    order = {'primary': 0, 'generated': 1, 'divided': 2, 'gated': 3}
    for name, c in sorted(by_clock.items(), key=lambda x: (order.get(x[1]['kind'], 4), x[0])):
        i = design.by_path.get(name)
        local = design.signals[i]['name'] if i is not None else name
        gen = (cfg.get('generated') or {}).get(name)
        if c['kind'] == 'primary':
            src = design.signals[design.by_path[c['source']]]['name']
            if name in periods or c['source'] in periods:
                p = periods.get(name, periods.get(c['source']))
                lines.append(f'create_clock -name {local} -period {p:g} [get_ports {{{src}}}]')
                defined[name] = dict(name=local, period=p, master=c['master'], port=src)
            else:
                emit('sdc.unconstrained_clock', name, 'Primary clock has no period (Spinal FixedFrequency or sdc.clocks).',
                     severity='error')
        elif c['kind'] == 'divided' or gen:
            master = (gen or {}).get('source') or c.get('master')
            master_def = next((v for k, v in defined.items() if k == master or v['master'] == master), None)
            if not master_def:
                emit('sdc.unconstrained_clock', name, 'Derived clock has no defined master clock.', severity='error')
                continue
            ratio = ''
            if gen:
                ratio = ''.join(f' -{k} {gen[k]}' for k in ('multiply_by', 'divide_by') if k in gen)
            elif c.get('divide_by'):
                ratio = f" -divide_by {c['divide_by']}"
            else:
                emit('sdc.unknown_ratio', name, 'Divided clock ratio is unknown; declare it in sdc.generated.')
                continue
            target = (f"[get_pins {{{names.cell(design.by_path[c['source']])}/{names.pin}}}]"
                      if c['kind'] == 'divided' else f'[get_pins {{{names.hier(i)}}}]')
            lines.append(f"create_generated_clock -name {local} -source [get_ports {{{master_def['port']}}}]{ratio} {target}")
            defined[name] = dict(name=local, period=None, master=master_def['master'], port=master_def['port'])
        elif c['kind'] == 'gated':
            lines.append(f'# {local}: gated from {c["source"]}; STA propagates the master clock through the gate.')
            if c.get('master') in {v['master'] for v in defined.values()}:
                base = next(v for v in defined.values() if v['master'] == c['master'])
                defined[name] = dict(base, period=None)
        else:
            emit('sdc.unconstrained_clock', name, f"Clock kind {c['kind']} needs a declaration in sdc.generated.",
                 severity='error')

    # Spinal-declared synchronous clocks (setSynchronousWith) are recorded, not grouped.
    spinal_sync = sorted({m.groups() for x in design.signals.values() for m in SYNCTAG.finditer(x.get('tags') or '')})

    # Crossing exceptions from Spinal tags and recognized safe structures.
    excepted, unsafe = [], []
    for row in s['crossings']:
        src, dst = design.by_path[row['source']], design.by_path[row['destination']]
        tags = design.signals[dst].get('tags') or ''
        kind = row['kind']
        if kind == 'synchronous_related':
            continue
        m = MAXDELAY.search(tags)
        if kind in SAFE:
            if m and row['relationship'] != 'unknown':
                cycles, target = int(m.group(1)), m.group(2) == 'true'
                clock = row['destination_domain'] if target else row['source_domain']
                cname = (design.domains.get(clock) or {}).get('clock')
                p = (defined.get(cname) or {}).get('period')
                if p:
                    lines.append(f'set_max_delay -datapath_only {cycles * p:g} -from {names.cells(src)} -to {names.cells(dst)}')
                else:
                    emit('sdc.unresolved_max_delay', row['destination'],
                         'Spinal crossClockMaxDelay needs the clock period.', severity='warning')
                    continue
            else:
                lines.append(f'set_false_path -from {names.cells(src)} -to {names.cells(dst)}')
            excepted.append(row)
        elif kind in UNSAFE:
            unsafe.append(row)
            emit('sdc.unsafe_crossing', row['destination'],
                 f'Crossing class {kind} gets no timing exception. Fix the crossing before constraining it.')
    for x in design.signals.values():
        for m in FALSEPATH.finditer(x.get('tags') or ''):
            dest_type, source = m.group(1), m.group(2)
            i = design.by_path[x['path']]
            if source and source in design.by_path and design.is_top_input(design.by_path[source]):
                frm = f" -from [get_ports {{{design.signals[design.by_path[source]]['name']}}}]"
            else:
                frm = ''
            lines.append(f'set_false_path{frm} -to {names.cells(i)}  ;# Spinal crossClockFalsePath {dest_type}')

    # Declared multicycle paths must match an elaborated register path.
    for mc in cfg.get('multicycle') or []:
        a, b = design.by_path.get(mc['from']), design.by_path.get(mc['to'])
        if a not in design.regs or b not in design.regs or a not in design.upstream_regs(b):
            emit('sdc.unmatched_multicycle', mc['to'], f"No register path {mc['from']} -> {mc['to']}.", severity='error')
            continue
        hold = mc.get('hold', mc['setup'] - 1)
        lines.append(f"set_multicycle_path {mc['setup']} -setup -from {names.cells(a)} -to {names.cells(b)}  ;# {mc['reason']}")
        lines.append(f"set_multicycle_path {hold} -hold -from {names.cells(a)} -to {names.cells(b)}")

    # Clock groups only between masters whose every crossing is excepted as safe.
    masters = sorted({v['master'] for v in defined.values() if v['master']})
    groups = []
    for n, a in enumerate(masters):
        for b in masters[n + 1:]:
            pair = [r for r in s['crossings'] if {clock_master(clocks, r['source_domain']),
                                                  clock_master(clocks, r['destination_domain'])} == {a, b}]
            if pair and all(r in excepted for r in pair):
                groups.append((a, b))
    for a, b in groups:
        ga = ' '.join(sorted({v['name'] for v in defined.values() if v['master'] == a}))
        gb = ' '.join(sorted({v['name'] for v in defined.values() if v['master'] == b}))
        lines.append(f'# All crossings {a} <-> {b} are recognized structures; timing exceptions above already cover them.')
        lines.append(f'# set_clock_groups -asynchronous -group {{{ga}}} -group {{{gb}}}')

    checked = check(cfg['check'], design, names, s, defined, emit) if cfg.get('check') else None
    return dict(status='completed', findings=findings, sdc='\n'.join(lines) + '\n', clocks=defined,
                spinal_synchronous=[list(p) for p in spinal_sync], excepted=len(excepted), unsafe=len(unsafe),
                check=checked, scope='logical timing intent from clock-domain data; not routed timing signoff')


def clock_master(clocks, domain):
    return next((c.get('master') for c in clocks if c['domain'] == domain), None)


def get_objects(text):
    """(kind, pattern) pairs from [get_* {a b}] or [get_* a] forms."""
    out = []
    for kind, body in re.findall(r'\[\s*get_(ports|cells|clocks|pins|nets)\s+(?:-\w+\s+)*([^\]]*)\]', text):
        body = body.strip().strip('{}')
        out.extend((kind, p) for p in body.split())
    return out


def check(path, design, names, s, defined, emit):
    """Check a project SDC file against the design: clocks, endpoints and crossings."""
    from pathlib import Path
    text = Path(path).read_text()
    commands = []
    for raw in re.sub(r'\\\n', ' ', text).splitlines():
        line = raw.split(';#')[0].strip()
        if not line or line.startswith('#'):
            continue
        try:
            cmd = shlex.split(line.replace('[', ' [ ').replace(']', ' ] '), posix=False)[0]
        except ValueError:
            cmd = line.split()[0]
        commands.append((cmd, line))
    top_inputs = {design.signals[i]['name'] for i in design.signals if design.is_top_input(i)}
    design_clocks = {c['clock'] for c in s['cdc']['clocks']}
    cells = {names.hier(i): i for i in design.regs}
    sdc_clocks, exceptions, groups = {}, [], []
    for cmd, line in commands:
        objs = get_objects(line)
        if cmd == 'create_clock':
            m = re.search(r'-name\s+(\S+)', line)
            ports = [p for k, p in objs if k == 'ports']
            name = m.group(1) if m else (ports[0] if ports else None)
            for p in ports:
                if p not in top_inputs:
                    emit('sdc.unmatched_clock', p, f'create_clock targets {p}, which is not a toplevel input.', severity='error')
            sdc_clocks[name] = ports
        elif cmd == 'create_generated_clock':
            m = re.search(r'-name\s+(\S+)', line)
            sdc_clocks[m.group(1) if m else line] = []
        elif cmd in ('set_false_path', 'set_max_delay', 'set_multicycle_path'):
            frm = get_objects(line.split('-from', 1)[1].split('-to')[0]) if '-from' in line else []
            to = get_objects(line.split('-to', 1)[1]) if '-to' in line else []
            for kind, pattern in frm + to:
                if kind == 'cells' and not any(fnmatch.fnmatchcase(names.pattern.format(path=c), pattern) or
                                               fnmatch.fnmatchcase(c, pattern) for c in cells):
                    emit('sdc.unmatched_endpoint', pattern, f'{cmd} names no design register: {pattern}.', severity='error')
                if kind == 'ports' and pattern not in top_inputs and not any(
                        design.signals[i]['name'] == pattern for i in design.signals if design.is_top_output(i)):
                    emit('sdc.unmatched_endpoint', pattern, f'{cmd} names no toplevel port: {pattern}.', severity='error')
            exceptions.append((cmd, frm, to))
        elif cmd == 'set_clock_groups' and '-asynchronous' in line or cmd == 'set_clock_groups' and '-logically_exclusive' in line:
            parts = re.findall(r'-group\s+(\{[^}]*\}|\[[^\]]*\]|\S+)', line)
            groups.append([set(re.findall(r'[\w./$*]+', p)) - {'get_clocks'} for p in parts])
    for c in sorted(defined):
        name = defined[c]['name']
        if name not in sdc_clocks and not any(name in ports for ports in sdc_clocks.values()):
            emit('sdc.unconstrained_clock', c, f'Design clock {name} has no clock in the SDC file.', severity='error')
    for name, ports in sdc_clocks.items():
        if ports and not any(p in {design.signals[design.by_path[x]]['name'] for x in design_clocks if x in design.by_path}
                             for p in ports):
            emit('sdc.unmatched_clock', name, f'SDC clock {name} drives no design clock domain.', severity='error')

    def matches(objs, i):
        return any(kind == 'cells' and (fnmatch.fnmatchcase(names.cell(i), p) or fnmatch.fnmatchcase(names.hier(i), p))
                   for kind, p in objs)

    def clock_name(domain):
        cname = (design.domains.get(domain) or {}).get('clock')
        return (defined.get(cname) or {}).get('name')

    covered = 0
    for row in s['crossings']:
        if row['kind'] == 'synchronous_related':
            continue
        src, dst = design.by_path[row['source']], design.by_path[row['destination']]
        a, b = clock_name(row['source_domain']), clock_name(row['destination_domain'])
        hit = any((not frm or matches(frm, src) or any(k == 'clocks' and p == a for k, p in frm)) and
                  (not to or matches(to, dst) or any(k == 'clocks' and p == b for k, p in to)) and (frm or to)
                  for cmd, frm, to in exceptions if cmd in ('set_false_path', 'set_max_delay'))
        hit |= any(any(a in g for g in grp) and any(b in g for g in grp) and
                   next(n for n, g in enumerate(grp) if a in g) != next(n for n, g in enumerate(grp) if b in g)
                   for grp in groups)
        if hit:
            covered += 1
            if row['kind'] in UNSAFE:
                emit('sdc.unsafe_false_path', row['destination'],
                     f"SDC exception covers an unsafe {row['kind']} crossing. It hides a CDC fault from STA.",
                     severity='error')
        elif row['relationship'] in ('asynchronous', 'declared_asynchronous', 'unknown'):
            emit('sdc.unconstrained_crossing', row['destination'],
                 'Crossing between unrelated clocks has no SDC exception. STA times it with an arbitrary relationship.')
    return dict(path=str(path), commands=len(commands), clocks=sorted(sdc_clocks), covered_crossings=covered)


def run(db_path, cfg, intent):
    from rvw.query.db import run_on
    return run_on(db_path, lambda db: analyze(db, cfg, intent))

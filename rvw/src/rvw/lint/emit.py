"""Functional CDC step: protocol assertions for simulation and formal, from CDC obligations.

`cdc_checks.sv` holds checker modules and `bind` lines (Verilator and other simulators).
`checked/` holds RTL copies with the checker instances inside the target modules, for flows
without `bind` (Yosys, `rvw formal`). Emitted assertions are obligations, not results."""
import hashlib
import json
from pathlib import Path
import re


CHECKERS = '''// Generated by rvw lint --emit. Obligations, not results.
module rvw_cdc_gray #(parameter W = 1) (input clk, input [W-1:0] value);
  reg past_valid = 1'b0;
  reg [W-1:0] last;
  wire [W-1:0] diff = value ^ last;
  always @(posedge clk) begin past_valid <= 1'b1; last <= value; end
  // At most one bit changes per source clock: (diff & (diff - 1)) == 0.
  always @(posedge clk) if (past_valid) assert ((diff & (diff - 1'b1)) == {W{1'b0}});
endmodule

module rvw_cdc_stable #(parameter W = 1) (input clk, input qualifier, input [W-1:0] value);
  reg past_valid = 1'b0;
  reg q_last;
  reg [W-1:0] v_last;
  always @(posedge clk) begin past_valid <= 1'b1; q_last <= qualifier; v_last <= value; end
  // Data is stable while the qualifier that crosses with it stays asserted.
  always @(posedge clk) if (past_valid && q_last && qualifier) assert (value == v_last);
endmodule
'''
MODULES = {'gray_code': 'rvw_cdc_gray', 'data_stable': 'rvw_cdc_stable'}


def instance(ob):
    b = ob['bind']
    ports = ', '.join(f'.{k}({v})' for k, v in b['ports'].items())
    return f"{MODULES[ob['kind']]} #(.W({ob['width']})) rvw_{ob['id']} ({ports});"


def write(report, files, out):
    out = Path(out)
    if out.exists() and any(out.iterdir()):
        raise ValueError(f'--emit directory must be new or empty: {out}')
    out.mkdir(parents=True, exist_ok=True)
    cdc = report['backends'].get('structural', {}).get('cdc') or {}
    obligations = cdc.get('obligations', [])
    bound = [o for o in obligations if o.get('bind')]
    lines = [CHECKERS] + [f"bind {o['bind']['module']} {instance(o)}" for o in bound]
    (out / 'cdc_checks.sv').write_text('\n'.join(lines) + '\n')
    checked = []
    if files and bound:
        (out / 'checked').mkdir()
        by_module = {}
        for o in bound:
            by_module.setdefault(o['bind']['module'], []).append(instance(o))
        placed = set()
        for f in files:
            text = Path(f).read_text()
            for module, insts in by_module.items():
                m = re.search(rf'^\s*module\s+{re.escape(module)}\b', text, re.M)
                if not m:
                    continue
                end = text.index('endmodule', m.end())
                text = text[:end] + ''.join(f'  {i}\n' for i in insts) + text[end:]
                placed.add(module)
            dest = out / 'checked' / Path(f).name
            dest.write_text(text)
            checked.append(str(dest))
        (out / 'checked' / 'rvw_cdc_checkers.sv').write_text(CHECKERS)
        checked.append(str(out / 'checked' / 'rvw_cdc_checkers.sv'))
        for o in bound:
            o['placed'] = o['bind']['module'] in placed
    manifest = dict(schema='rvw.cdc-obligations/1', config=report['config'], top=report['top'],
                    status='obligations' if obligations else 'no_checks', obligations=obligations,
                    checks='cdc_checks.sv', checked_rtl=checked,
                    unbound=[o['id'] for o in obligations if not o.get('bind')],
                    note='Run checked_rtl with rvw formal bmc/prove or a simulator with --assert. '
                         'Emission is not a pass.')
    data = json.dumps(manifest, indent=2, sort_keys=True)
    (out / 'cdc_obligations.json').write_text(data + '\n')
    return dict(dir=str(out), obligations=len(obligations), bound=len(bound),
                sha256=hashlib.sha256(data.encode()).hexdigest())

"""Scaffold a non-Spinal core project: SystemVerilog, VHDL or Chisel (FIRRTL).

Writes `rvw.toml` with a `query.build` entry that runs `rvw query build-hdl` with the right
front end, a Verilator C1 launcher whose `info` and `build` work and whose `run` refuses until
the memory and completion mapping exists, and a harness skeleton that compiles for any top."""
from __future__ import annotations

import json
from pathlib import Path
from .inputs import INPUT_ENV, INPUT_COMMANDS
import re
import shlex

import rvw

SKIP_DIRS = {'tb', 'test', 'tests', 'dv', 'sim', 'verif', 'bench', 'examples', 'doc', 'docs', 'syn',
             'fpga', 'formal', 'rvw', 'out', 'build', 'target', '.git'}
SUFFIX = {'sv': ('.sv', '.v'), 'vhdl': ('.vhd', '.vhdl')}
FRONTEND = {'sv': 'slang', 'vhdl': 'ghdl', 'chisel': 'chisel'}


def _discover(root: Path, hdl: str) -> list[Path]:
    """HDL files under the root outside test and tool directories; packages first."""
    found = [p for p in sorted(root.rglob('*')) if p.suffix in SUFFIX[hdl] and p.is_file()
             and not (set(p.relative_to(root).parts[:-1]) & SKIP_DIRS)]
    if hdl == 'sv':
        found = [p for p in found if not p.name.endswith('.svh')]
        key = lambda p: (0 if re.search(r'^\s*package\b', p.read_text(errors='replace'), re.M) else 1, str(p))
    else:
        key = lambda p: (0 if re.search(r'^\s*package\s+\w+\s+is\b', p.read_text(errors='replace'), re.M | re.I)
                         and not re.search(r'^\s*entity\b', p.read_text(errors='replace'), re.M | re.I) else 1, str(p))
    return sorted(found, key=key)


def _modules(paths, hdl):
    pattern = r'^\s*module\s+(\w+)' if hdl == 'sv' else r'^\s*entity\s+(\w+)\s+is\b'
    return sorted({m for p in paths for m in re.findall(pattern, p.read_text(errors='replace'), re.M | re.I)})


def scaffold_hdl(path='.', *, hdl, top, isa, name=None, sources=(), include_dirs=(), library='work',
                 fir=None, source_roots=(), force=False, dry_run=False):
    root = Path(path).resolve()
    if not root.is_dir():
        raise ValueError(f'not a directory: {root}')
    if hdl not in FRONTEND:
        raise ValueError('--hdl is sv, vhdl or chisel')
    if not top or re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', top) is None:
        raise ValueError('supply --top: the toplevel module, entity or Chisel module name')
    if not isa:
        raise ValueError('supply --isa from the core specification')
    isa = isa.lower()
    if re.fullmatch(r'rv(32|64)[ieg][a-z]*(?:_[a-z][a-z0-9]*)*', isa) is None:
        raise ValueError('ISA must start with rv32 or rv64 and an i, e or g base')
    width = int(isa[2:4])
    name = name or root.name
    if re.fullmatch(r'[a-zA-Z][a-zA-Z0-9_-]*', name) is None:
        raise ValueError('Core name must start with a letter and contain letters, digits, _ or -.')
    rel = lambda p: Path(p).resolve().relative_to(root).as_posix() if Path(p).resolve().is_relative_to(root) \
        else str(Path(p).resolve())
    if hdl == 'chisel':
        if not fir:
            raise ValueError('supply --fir: the FIRRTL file the core build emits (ChiselStage.emitCHIRRTL)')
        files_in = [rel(root / fir)]
        roots = [rel(root / r) for r in source_roots] or ['src/main/scala']
        modules = []
    else:
        chosen = [root / s for s in sources] if sources else _discover(root, hdl)
        if not chosen:
            raise ValueError(f'no {hdl} sources found; pass --source FILE')
        missing = [str(p) for p in chosen if not p.is_file()]
        if missing:
            raise ValueError('missing sources: ' + ', '.join(missing))
        modules = _modules(chosen, hdl)
        if top.lower() not in {m.lower() for m in modules}:
            raise ValueError(f'top {top!r} is not declared in the sources; candidates: {", ".join(modules) or "none"}')
        files_in = [rel(p) for p in chosen]
        roots = []
    incs = [rel(root / d) for d in include_dirs]
    q, sh = json.dumps, shlex.quote
    frontend = FRONTEND[hdl]
    args = [f'--frontend {frontend}', f'--top {sh(top)}', *(f'-I {sh(i)}' for i in incs),
            *([f'--library {sh(library)}'] if hdl == 'vhdl' else []),
            *(f'--source-root {sh(r)}' for r in roots)]
    lines = ' \\\n  '.join([*args, *map(sh, files_in)])
    build_db = f'''#!/usr/bin/env bash
# rvw query build CONFIG OUT: design database of {top} ({hdl}, frontend {frontend}).
# Review the source list and order; generated by rvw init --hdl {hdl}.
set -euo pipefail
cd "$(dirname "$0")/.."
out="${{2:?usage: build-db.sh CONFIG OUT}}"
exec "${{RVW:-rvw}}" query build-hdl --out "$out" \\
  {lines}
'''
    info = dict(schema='rvw.adapter/1', core=name, configs=['default'], default_config='default',
                xlen=width, isa={'default': isa}, scaffold=True, hdl=hdl, top=top)
    if hdl == 'sv':
        rtl = 'rtl=(' + ' '.join(sh(f) for f in files_in) + ')\n' + \
              'incs=(' + ' '.join(sh('-I' + i) for i in incs) + ')\n'
    elif hdl == 'vhdl':
        # Verilator reads Verilog: GHDL synthesizes the VHDL, Yosys writes it.
        rtl = f'''mkdir -p rvw/out
srcs=({' '.join(sh(f) for f in files_in)})
yosys -q -m "${{RVW_GHDL_PLUGIN:-ghdl}}" -p "ghdl --std=08 --work={library} ${{srcs[*]}} -e {top}; write_verilog -noattr rvw/out/{top}.v"
rtl=(rvw/out/{top}.v)
incs=()
'''
    else:
        rtl = f'''mkdir -p rvw/out/rtl
"${{RVW_FIRTOOL:-firtool}}" {sh(files_in[0])} --split-verilog -o rvw/out/rtl --disable-all-randomization
rtl=($(sed 's#^#rvw/out/rtl/#' rvw/out/rtl/filelist.f))
incs=()
'''
    launcher = f'''#!/usr/bin/env bash
# C1 launcher scaffold for {name} ({hdl}). info and build work; run refuses until mapped.
set -euo pipefail
cd "$(dirname "$0")/.."
cmd="${{1:-}}"
if [ "$cmd" = info ]; then
  cat <<'RVW_INFO'
{json.dumps(info)}
RVW_INFO
  exit 0
fi
if [ "$cmd" = build ]; then
  mkdir -p rvw/out/obj_dir
  {rtl.strip().replace(chr(10), chr(10) + '  ')}
  verilator --cc --exe --build -O2 -Wno-fatal --top-module {top} -Mdir rvw/out/obj_dir \\
    "${{incs[@]}}" "${{rtl[@]}}" "$PWD/rvw/sim/harness.cpp" -o sim >&2
  printf '%s\\n' '{{"schema":"rvw.build/1","status":"built","model":"rvw/out/obj_dir/sim"}}'
  exit 0
fi
printf '%s\\n' 'run is not mapped: drive reset and clock, serve the instruction and data buses, detect tohost completion and write C1 result.json in rvw/sim/harness.cpp. See rvw/README.md.' >&2
exit 2
'''
    if hdl == 'sv':
        launcher = launcher[:launcher.index('if [ "$cmd" = build ]; then')] + f'''if [ "$cmd" = build ] || [ "$cmd" = identity ]; then
  shift
  exec "${{RVW_PYTHON:-${{RVW_HOME:?set RVW_HOME}}/rvw/.venv/bin/python}}" -m rvw.init.hdl_identity rvw/hdl.json "$cmd" "$@"
fi
printf '%s\\n' 'run is not mapped: complete rvw/sim/harness.cpp and bind its C1 claims to rvw/hdl.json' >&2
exit 2
'''
    harness = f'''// Verilator harness skeleton for {top}. It compiles for any top and maps nothing.
// Map: clock and reset, instruction/data bus to an ELF-loaded memory, tohost completion,
// and the C1 result (docs/contracts/c1-run.md). Until then it refuses with exit 2.
#include <cstdio>
#include "V{top}.h"
#include "verilated.h"

int main(int argc, char** argv) {{
  Verilated::commandArgs(argc, argv);
  V{top} top;
  top.eval();
  std::fprintf(stderr, "harness not mapped: see rvw/README.md\\n");
  return 2;
}}
'''
    config = f'''[project]
schema = "rvw.project/1"
rvw_version = {q(rvw.__version__)}
root = "."

[core]
name = {q(name)}
adapter = "./rvw/run.sh"
configs = ["default"]
default_config = "default"
source_repo = "."
lock = {q(name)}
input_complete = false
identity = false
identity_capture = false
jobs = 1

[suites.smoke]
dir = "rvw/out/programs"
include = ['^smoke$']
max_cycles = 10000
timeout_s = 60

[tiers.quick]
runs = [{{ suite = "smoke" }}]

[query]
build = ["./rvw/build-db.sh"]
db = "rvw/out/design.db"
'''
    tools = {'sv': 'Yosys with the yosys-slang plugin (RVW_SLANG or OSS CAD Suite)',
             'vhdl': 'Yosys, GHDL and a GHDL Yosys plugin (RVW_GHDL_PLUGIN; scripts/build-ghdl-plugin.py)',
             'chisel': 'Yosys and firtool (RVW_FIRTOOL); the core build must emit the FIRRTL file first'}[hdl]
    readme = f'''# Core setup playbook ({hdl})

Generated by `rvw init --hdl {hdl}` for top `{top}`. Needs {tools}, and Verilator for `build`.

Design queries work now:

```sh
rvw query build --config default        # runs rvw/build-db.sh, writes rvw/out/design.db
rvw query hierarchy --db rvw/out/design.db
rvw lint --db rvw/out/design.db         # structural CDC/RDC on the same database
```

1. Review the source list and order in `rvw/build-db.sh` and `rvw/run.sh` (packages first).
2. Check the ISA ({isa}) and XLEN against the core specification.
3. `rvw/run.sh build` compiles the design with Verilator and `rvw/sim/harness.cpp`.
4. Map clock, reset, the instruction and data buses, ELF loading and tohost completion
   in the harness. Write C1 `result.json` (docs/contracts/c1-run.md). `run` refuses until then.
5. Build one smoke ELF at rvw/out/programs/smoke. Run `rvw doctor --json`.
6. Map C2 RVFI from retired effects before cosim. Review all inputs before `input_complete`.
'''
    files = {'rvw.toml': config, 'rvw/run.sh': launcher, 'rvw/build-db.sh': build_db,
             'rvw/sim/harness.cpp': harness, 'rvw/.gitignore': '/out/\n', 'rvw/README.md': readme}
    if hdl == 'sv':
        files['rvw/hdl.json'] = json.dumps(dict(top=top, sources=files_in, include_dirs=incs,
            defines=[], verilator_flags=['-O2', '-Wno-fatal'],
            harness_sources=['rvw/sim/harness.cpp'], build_dir='rvw/out/obj_dir'), indent=2) + '\n'
        files['rvw.toml'] = config.replace('input_complete = false', 'input_complete = true').replace('identity = false', 'identity = true').replace(
            'identity_capture = false', 'identity_capture = true') + '\n'
        files['rvw.toml'] = files['rvw.toml'].replace('jobs = 1',
            'cache_paths = ' + q(['rvw/hdl.json', 'rvw/run.sh', 'rvw/sim/harness.cpp', *files_in, *incs]) + '\n'
            'input_tools = ["verilator", "make", "git"]\ninput_verilator_toolchain = true\n'
            'input_env = ' + INPUT_ENV + '\ninput_commands = ' + INPUT_COMMANDS.replace('\"sbt\", ', '') + '\njobs = 1')
    conflicts = [key for key in files if (root / key).exists() or (root / key).is_symlink()]
    if conflicts and not force:
        raise ValueError('Refusing to overwrite: ' + ', '.join(conflicts) + '. Use --force only for intended replacement.')
    for key in files:
        if (root / key).is_dir():
            raise ValueError(f'Refusing to replace directory: {root / key}')
    if not dry_run:
        for key, content in files.items():
            target = root / key
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
            if key.endswith('.sh'):
                target.chmod(0o755)
    return dict(schema='rvw.init/1', status='planned' if dry_run else 'created', exit_code=0, root=str(root),
                hdl=hdl, frontend=frontend, top=top, isa=isa, xlen=width, sources=files_in,
                candidate_tops=modules, files=files, overwritten=conflicts if force else [],
                next=['Run rvw query build --config default; every rvw query and lint command then works.',
                      'Review rvw/build-db.sh sources, then map rvw/sim/harness.cpp for C1 runs.'])

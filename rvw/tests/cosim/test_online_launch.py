"""Launch fixtures exercise process ownership, live tailing and offline parity."""
import json
import os
from pathlib import Path
import sys
import time
import pytest
from rvw.cosim.online import launch_online
from rvw.cosim.platform import Platform
from test_state import fixture, Model

IDENTITY = dict(elf_sha256='a', platform_sha256='b', capture={}, tools={})


def producer(tmp_path, records, *, delay=0, code=0):
    text = ''.join(json.dumps(r)+'\n' for r in records)
    output = tmp_path / 'out'
    command = [sys.executable, '-c',
               'import os,time; from pathlib import Path; '
               'assert os.environ["RVW_RVFI_FLUSH"] == "1"; '
               f'p=Path({str(output / "rvfi.jsonl")!r}); '
               f'p.write_text({text!r}); time.sleep({delay}); raise SystemExit({code})']
    return output, command


def test_launch_mismatch_stops_before_simulator_finishes(tmp_path):
    h, row = fixture()
    row['fd_wdata'] = '0x1'
    out, command = producer(tmp_path, [h, row, dict(event='end', cycle=2, status='pass')], delay=60)
    before = time.monotonic()
    result = launch_online(command, Model(fixture()[1]), Platform.load('boom'), out=out,
                           reproduction=IDENTITY, timeout=5)
    assert time.monotonic()-before < 4
    assert result['status'] == 'mismatch'
    assert result['simulator']['returncode'] != 0
    assert not result['simulator']['timed_out']
    assert (out / 'rvfi.jsonl').exists()



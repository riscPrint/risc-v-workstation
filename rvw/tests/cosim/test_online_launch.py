def test_cli_live_native(tmp_path, tmp_path_factory):
    from argparse import Namespace
    from cosim_build import _build
    from rvw.cosim.cli import calculate
    source = tmp_path / 'nop.S'
    source.write_text('.section .text\n.globl _start\n_start:\n nop\n nop\n')
    elf = _build(tmp_path_factory, source)
    h, row = fixture()
    h['schema'] = 'rvw.rvfi/1'
    row = {key: value for key, value in row.items() if key not in ('fd_valid', 'fd', 'fd_wdata', 'fflags', 'fcsr')}
    out = tmp_path / 'cli-out'
    # Explicit independent expected NOP effect, not a trace generated by Spike.
    records = [h, row, dict(event='end', cycle=2, status='pass')]
    script = tmp_path / 'adapter.py'
    script.write_text('import sys\nfrom pathlib import Path\n'
                      'assert Path(sys.argv[1]).read_bytes()[:4] == b"\\x7fELF"\n'
                      f'Path(sys.argv[2], "rvfi.jsonl").write_text({"".join(json.dumps(r)+chr(10) for r in records)!r})\n')
    result, code = calculate(Namespace(cosim_action='live', elf=elf, core='boom', platform=None,
        model='spike', history=10, strict=False, strict_sync=(), timeout=5, sail_config=None,
        out=out, simulator=[sys.executable, str(script), '{elf}', '{out}']))
    assert (result['status'], code) == ('match', 0), result
    assert result['mode'] == 'online'
    assert result['trace_complete']
    assert 'trace_sha256' not in result['reproduction']
    assert result['reproduction']['elf_sha256']
    assert '--simulator' in result['reproduction']['replay']



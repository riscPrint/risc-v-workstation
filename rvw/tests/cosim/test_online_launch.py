def test_parse_error_kills_term_resistant_producer(tmp_path):
    script = ('import signal,time; from pathlib import Path; '
              'signal.signal(signal.SIGTERM, signal.SIG_IGN); '
              f'Path({str(tmp_path / "bad" / "rvfi.jsonl")!r}).write_text("bad\\n"); '
              'time.sleep(60)')
    start = time.monotonic()
    with pytest.raises(ValueError):
        launch_online([sys.executable, '-c', script], Model(fixture()[1]), Platform.load('boom'),
                      out=tmp_path / 'bad', reproduction=IDENTITY, timeout=5, grace=0.1)
    assert time.monotonic()-start < 4



def test_adapter_supervisor_reaps_its_separate_group(tmp_path):
    import shlex
    h, row = fixture()
    row['fd_wdata'] = '0x1'
    out = tmp_path / 'supervised'
    text = ''.join(json.dumps(r)+'\n' for r in [h, row, dict(event='end', cycle=2, status='pass')])
    pid = tmp_path / 'nested.pid'
    script = tmp_path / 'adapter.py'
    script.write_text('import os,time\nfrom pathlib import Path\n'
                      f'Path({str(pid)!r}).write_text(str(os.getpid()))\n'
                      f'Path({str(out / "rvfi.jsonl")!r}).write_text({text!r})\n'
                      'time.sleep(60)\n')
    shell = tmp_path / 'adapter.sh'
    shell.write_text('exec '+shlex.join([sys.executable, str(script)])+'\n')
    supervisor = Path(__file__).resolve().parents[3] / 'RiscvSim/scripts/supervise.py'
    result = launch_online([sys.executable, str(supervisor), '/bin/bash', str(shell)],
                           Model(fixture()[1]), Platform.load('boom'), out=out,
                           reproduction=IDENTITY, timeout=10)
    assert result['status'] == 'mismatch'
    with pytest.raises(ProcessLookupError):
        os.kill(int(pid.read_text()), 0)

#!/usr/bin/env python3
"""Generate the untested Linux recipe table from the tool inventory."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def render():
    data=json.loads((ROOT/'rvw/src/rvw/doctor/tools.json').read_text())
    lines=['# Linux install recipes', '', 'Linux execution is untested. No Linux host was available for this change.',
           'Package names can vary by distribution release. A listed package is not a',
           'version pin. Use the source recipe when a package is absent or incompatible.',
           'Do not treat a dry-run on macOS as a Linux install result.', '',
           'Generated by `python3 scripts/generate-linux-docs.py` from the shared inventory.', '',
           '| Tool | Flag | apt packages | dnf packages | Source or fallback |',
           '|---|---|---|---|---|']
    for t in data['tools']:
        i=t['install'];lines.append(f"| {t['name']} | `--with-{t['flag']}` | {i['apt'] or 'No verified distro package'} | {i['dnf'] or 'No verified distro package'} | {i['source'] or 'Use the listed distro package; source pin unverified'} |")
    lines += ['', '## Check before installation', '', '```sh',
              'scripts/install.sh --profile verification --dry-run',
              'scripts/install.sh --profile formal --check',
              'python3 scripts/tool-inventory.py --linux-plan apt --extra openocd ghdl qemu',
              'python3 scripts/tool-inventory.py --linux-plan dnf --extra openocd ghdl qemu',
              '```', '',
              'Base flags retain their existing apt/dnf source-build paths in `install.sh`.',
              'New package-backed flags use the same package approval path. Source-only',
              'flags print manual instructions and fail unless the tool is already present.',
              'GHDL needs both libghdl and a plugin built for the selected Yosys ABI.',
              'The plugin builder records its selected GHDL commit. Its default plugin',
              'revision was tested against an older OSS CAD Suite; current-suite Linux',
              'compatibility is not established.', '',
              'Use `python3 scripts/qualify-install.py --case all --out /tmp/rvw-all`',
              'on a fresh native Linux host to collect actual results. Do not run this',
              'long qualification on the shared Mac. #17 stays open.', '']
    return '\n'.join(lines)
if __name__=='__main__':(ROOT/'docs/LINUX_INSTALL.md').write_text(render())
